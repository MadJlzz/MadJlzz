// index.js
const Mustache = require('mustache');
const fs = require('fs');
const MUSTACHE_MAIN_DIR = './main.mustache';
const BLOG_RSS_URL = 'https://www.julienklaer.dev/rss.xml';
const MAX_POSTS = 5;

/**
  * The output is markdown, not HTML: keep characters like '/' as-is
  * instead of letting Mustache turn them into '&#x2F;'.
*/
Mustache.escape = (text) => String(text);

/**
  * DATA is the object that contains all
  * the data to be provided to Mustache.
  * "posts" and "projects" are filled at build time
  * from the blog RSS feed and the GitHub API.
*/
let DATA = {
    firstname: 'julien',
    githubUsername: 'MadJlzz',
    stack: ['golang', 'python', 'terraform', 'ansible', 'k8s', 'otel', 'gcp', 'azure', 'aws'].join(' · '),
    repositories: [
        'maddock',
        'madlab',
        'terraform-provider-oneprovider',
        'provider-oneprovider',
        'ansible-runner-operator',
        'dotfiles',
    ],
    year: new Date().getFullYear(),
};

const decodeXml = (text) => text
    .replace(/^<!\[CDATA\[([\s\S]*)\]\]>$/, '$1')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&(apos|#39);/g, "'")
    .replace(/&amp;/g, '&');

/**
  * Latest posts from the blog RSS feed.
  * The feed is small and generated by Astro, a regex is enough.
  */
async function fetchPosts() {
    const res = await fetch(BLOG_RSS_URL);
    if (!res.ok) throw new Error(`${BLOG_RSS_URL}: HTTP ${res.status}`);
    const xml = await res.text();
    const tag = (item, name) => decodeXml((item.match(new RegExp(`<${name}>([\\s\\S]*?)</${name}>`)) || [])[1] || '');
    return [...xml.matchAll(/<item>([\s\S]*?)<\/item>/g)]
        .map(([, item]) => ({
            title: tag(item, 'title'),
            link: tag(item, 'link'),
            excerpt: tag(item, 'description'),
            date: new Date(tag(item, 'pubDate')).toISOString().slice(0, 10),
        }))
        .sort((a, b) => b.date.localeCompare(a.date))
        .slice(0, MAX_POSTS);
}

/**
  * Description, language and stars of the featured repositories,
  * so the README follows whatever is set on GitHub.
  */
async function fetchProjects(repositories) {
    const headers = { Accept: 'application/vnd.github+json' };
    if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
    return Promise.all(repositories.map(async (name) => {
        const url = `https://api.github.com/repos/${DATA.githubUsername}/${name}`;
        const res = await fetch(url, { headers });
        if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
        const repo = await res.json();
        return {
            name: repo.name,
            url: repo.html_url,
            description: repo.description,
            language: repo.language && repo.language.toLowerCase(),
            stars: repo.stargazers_count,
        };
    }));
}

/**
  * A - We fetch the posts and projects
  * B - We ask Mustache to render 'main.mustache' with the data
  * C - We create a README.md file with the generated output
  */
async function generateReadMe() {
    const [posts, projects] = await Promise.all([fetchPosts(), fetchProjects(DATA.repositories)]);
    const template = fs.readFileSync(MUSTACHE_MAIN_DIR).toString();
    const output = Mustache.render(template, { ...DATA, posts, projects });
    fs.writeFileSync('README.md', output);
}

generateReadMe().catch((err) => {
    console.error(err);
    process.exit(1);
});
